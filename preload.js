const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  // barra de cada conta
  setLevel: (i, lv) => ipcRenderer.send('level-set', i, lv),
  perfMenu: (i, rect) => ipcRenderer.send('perf-menu', i, rect || null),
  setAuto: () => {},
  setLives: (i, plat, on) => ipcRenderer.send('lives-set', i, plat, on),
  openAutoConfig: () => {},
  onAutoCfg: () => {},
  autoCfgClosed: (id) => ipcRenderer.send('title-autocfg-closed', id),
  autoRunNow: () => {},
  autoLog: () => {},
  setView: (i) => ipcRenderer.send('view-set', i),
  reload: (i) => ipcRenderer.send('reload-account', i),
  toggleMute: (i) => ipcRenderer.send('mute-toggle', i),
  ready: () => ipcRenderer.send('bar-ready'),
  onState: (cb) => ipcRenderer.on('state', (_, s) => cb(s)),
  // compatibilidade neutra de configuração
  autoGet: () => Promise.resolve({ dry: false, rules: [] }),
  autoSave: () => Promise.resolve({ ok: true }),
  closeSelf: () => ipcRenderer.send('close-self'),
  // pontos da Kick
  kickGet: () => ipcRenderer.invoke('kick-get'),
  kickRefresh: () => ipcRenderer.invoke('kick-refresh'),
  kickRedeem: (i) => ipcRenderer.send('kick-redeem', i),
  kickRedeemLive: (i, slug) => ipcRenderer.send('kick-redeem-live', i, slug),
  kickSel: (i, slug) => ipcRenderer.send('kick-sel', i, slug),
  kickOpen: (i, rect) => ipcRenderer.send('kick-open', i, rect || null),
  onKickPanel: (cb) => ipcRenderer.on('title-kick', (_, d) => cb(d)),
  onLivesPanel: (cb) => ipcRenderer.on('title-lives', (_, d) => cb(d)),
  onExtsPanel: (cb) => ipcRenderer.on('title-exts', (_, d) => cb(d)),
  onExtsUpdate: (cb) => ipcRenderer.on('exts-update', () => cb()),
  extGet: () => ipcRenderer.invoke('ext-get'),
  extAction: (id, acao) => ipcRenderer.send('ext-action', id, acao),
  onLivesUpdate: (cb) => ipcRenderer.on('lives-update', () => cb()),
  livesGet: () => ipcRenderer.invoke('lives-get'),
  livesCheckNow: () => ipcRenderer.invoke('lives-check-now'),
  kickDiag: () => ipcRenderer.invoke('kick-diag'),
  onKickUpdate: (cb) => ipcRenderer.on('kick-update', () => cb()),
  // análise de PvP
  pvpGet: (i, force) => ipcRenderer.invoke('pvp-get', i, !!force),
  onPvpAccount: (cb) => ipcRenderer.on('pvp-account', (_, i) => cb(i)),
  // calculadora de Pokémon
  calcGet: (i, action, pokemon) => ipcRenderer.invoke('calc-get', i, action, pokemon),
  onCalcAccount: (cb) => ipcRenderer.on('calc-account', (_, i) => cb(i)),
  openCalc: (i) => ipcRenderer.send('calc-open', i),
  // barra de título customizada
  titleReady: () => ipcRenderer.send('title-ready'),
  titleOpen: (open) => ipcRenderer.send('title-open', !!open),
  titleClick: (pathIdx) => ipcRenderer.send('title-click', pathIdx),
  showAbout: () => ipcRenderer.send('show-about'),
  onDialog: (cb) => ipcRenderer.on('title-dialog', (_, d) => cb(d)),
  onPopup: (cb) => ipcRenderer.on('title-popup', (_, d) => cb(d)),
  popupReply: (id, value) => ipcRenderer.send('title-popup-reply', id, value),
  openLivePage: (i, plat, c) => ipcRenderer.send('live-page-open', i, plat, c),
  openExt: (i, id) => ipcRenderer.send('ext-open', i, id),
  onDialogClose: (cb) => ipcRenderer.on('title-dialog-close', (_, id) => cb(id)),
  dialogReply: (id, n, values) => ipcRenderer.send('title-dialog-reply', id, n, values || null),
  onTitleState: (cb) => ipcRenderer.on('title-state', (_, s) => cb(s)),
  onTitleBadges: (cb) => ipcRenderer.on('title-badges', (_, b) => cb(b)),
});
